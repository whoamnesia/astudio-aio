#!/usr/bin/env python3
"""astudio tokens - one brand spec -> W3C DTCG 2025.10 tokens + CSS variables + Tailwind v4 theme.

Usage
  tokens.py init > brand.spec.json            # print an annotated starter spec
  tokens.py build brand.spec.json --out design-tokens/
        writes  <slug>.tokens.json   (DTCG 2025.10: color objects, dimension objects, typography composites)
                tokens.css           (:root light + dark via prefers-color-scheme and [data-theme])
                tailwind-theme.css   (self-contained Tailwind v4 entry: @theme + light/dark vars; use instead of tokens.css)
  palette JSON from `palette.py system --json` can be referenced via "colors_from": "palette.json".

Spec keys (all optional except name/colors):
  name, colors{light{role:hex}, dark{role:hex}} | colors_from, fonts{display,body,mono},
  type{base_min,base_max,ratio_min,ratio_max,vw_min,vw_max,steps[]}, space{base,steps[]},
  radius{name:px}, shadow{name:css}, motion{durations{name:ms}, easings{name:[x1,y1,x2,y2]}}
Stdlib only.
"""
import argparse, json, re, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from palette import hex2rgb  # noqa: E402

STARTER = {
    "name": "Brand Name",
    "colors_from": "palette.json",
    "fonts": {"display": "Unbounded", "body": "Onest", "mono": "JetBrains Mono"},
    "type": {"base_min": 16, "base_max": 18, "ratio_min": 1.2, "ratio_max": 1.333, "vw_min": 390, "vw_max": 1440,
             "steps": ["xs", "sm", "base", "lg", "xl", "2xl", "3xl", "4xl", "5xl", "display"]},
    "space": {"base": 4, "steps": [0, 1, 2, 3, 4, 6, 8, 12, 16, 24, 32]},
    "radius": {"none": 0, "sm": 4, "md": 8, "lg": 16, "xl": 24, "full": 9999},
    "shadow": {"sm": "0 1px 2px rgb(0 0 0 / 0.06)", "md": "0 4px 12px -2px rgb(0 0 0 / 0.10)",
               "lg": "0 16px 40px -8px rgb(0 0 0 / 0.18)"},
    "motion": {"durations": {"press": 140, "hover": 180, "ui": 240, "reveal": 800, "open": 1200},
               "easings": {"out": [0.22, 1, 0.36, 1], "expo": [0.16, 1, 0.3, 1], "in-out": [0.76, 0, 0.24, 1],
                           "drawer": [0.32, 0.72, 0, 1], "exit": [0.55, 0.055, 0.675, 0.19]}},
}


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-") or "brand"


def dtcg_color(hexv):
    r, g, b = hex2rgb(hexv)
    return {"colorSpace": "srgb", "components": [round(r, 4), round(g, 4), round(b, 4)], "alpha": 1, "hex": hexv.lower()}


def dim(v, unit="px"):
    return {"value": v, "unit": unit}


def type_scale(t):
    """Fluid modular scale: each step = clamp(min, preferred, max) interpolated between two ratios."""
    steps = t["steps"]
    base_i = steps.index("base")
    out = {}
    for i, name in enumerate(steps):
        e = i - base_i
        if name == "display":
            e += 1.5  # display jumps well above 5xl
        mn = t["base_min"] * t["ratio_min"] ** e
        mx = t["base_max"] * t["ratio_max"] ** e
        mn, mx = sorted((round(mn, 2), round(mx, 2)))
        mn, mx = max(mn, 12.0), max(mx, 12.0)  # nothing readable goes below 12px
        slope = (mx - mn) / (t["vw_max"] - t["vw_min"])
        inter = mn - slope * t["vw_min"]
        pref = f"{inter / 16:.4f}rem + {slope * 100:.4f}vw"
        out[name] = {"min": mn, "max": mx, "css": f"clamp({mn / 16:.4f}rem, {pref}, {mx / 16:.4f}rem)"}
    return out


def build(spec, outdir):
    name = spec["name"]
    sl = slug(name)
    colors = spec.get("colors")
    if not colors and spec.get("colors_from"):
        p = Path(spec["colors_from"])
        if not p.is_absolute():
            p = Path(spec.get("_dir", ".")) / p
        pj = json.load(open(p))
        colors = {"light": pj.get("light"), "dark": pj.get("dark")}
        ramps = {k[5:]: v for k, v in pj.items() if k.startswith("ramp_")}
    else:
        ramps = {}
    if not colors or not colors.get("light"):
        sys.exit("spec needs colors.light (or colors_from palette.json)")
    fonts = spec.get("fonts", STARTER["fonts"])
    t = {**STARTER["type"], **spec.get("type", {})}
    sp = {**STARTER["space"], **spec.get("space", {})}
    radius = spec.get("radius", STARTER["radius"])
    shadow = spec.get("shadow", STARTER["shadow"])
    motion = {**STARTER["motion"], **spec.get("motion", {})}
    scale = type_scale(t)

    # ---- DTCG
    tok = {"$description": f"{name} design tokens (W3C DTCG 2025.10). Generated by astudio tokens.py.",
           "color": {"$type": "color"}}
    for k, ramp in ramps.items():
        tok["color"][k] = {str(step): {"$value": dtcg_color(v)} for step, v in ramp.items()}
    for mode, T in colors.items():
        if T:
            tok["color"][mode] = {role: {"$value": dtcg_color(v)} for role, v in T.items()}
    tok["font"] = {"family": {"$type": "fontFamily",
                              **{k: {"$value": [v, "system-ui", "sans-serif"] if k != "mono" else [v, "ui-monospace", "monospace"]}
                                 for k, v in fonts.items()}}}
    tok["font"]["size"] = {"$type": "dimension", **{k: {"$value": dim(v["max"]), "$description": f"fluid {v['css']}"}
                                                    for k, v in scale.items()}}
    tok["space"] = {"$type": "dimension", **{str(s): {"$value": dim(s * sp["base"])} for s in sp["steps"]}}
    tok["radius"] = {"$type": "dimension", **{k: {"$value": dim(v)} for k, v in radius.items()}}
    tok["duration"] = {"$type": "duration", **{k: {"$value": {"value": v, "unit": "ms"}} for k, v in motion["durations"].items()}}
    tok["easing"] = {"$type": "cubicBezier", **{k: {"$value": v} for k, v in motion["easings"].items()}}
    tok["typography"] = {
        "display": {"$type": "typography", "$value": {"fontFamily": "{font.family.display}", "fontSize": "{font.size.display}",
                                                     "fontWeight": 600, "letterSpacing": dim(-0.03, "rem"), "lineHeight": 0.98}},
        "heading": {"$type": "typography", "$value": {"fontFamily": "{font.family.display}", "fontSize": "{font.size.3xl}",
                                                     "fontWeight": 600, "letterSpacing": dim(-0.01, "rem"), "lineHeight": 1.1}},
        "body": {"$type": "typography", "$value": {"fontFamily": "{font.family.body}", "fontSize": "{font.size.base}",
                                                  "fontWeight": 400, "letterSpacing": dim(0, "rem"), "lineHeight": 1.55}},
    }

    # ---- CSS
    def cblock(T, ind):
        return "\n".join(f"{ind}--color-{k}: {v};" for k, v in T.items())
    css = [f"/* {name} tokens - generated by astudio tokens.py. Components use semantic vars only. */", ":root {",
           "  color-scheme: light;"]
    for k, ramp in ramps.items():
        css += [f"  --{k}-{s}: {v};" for s, v in ramp.items()]
    css.append(cblock(colors["light"], "  "))
    css += [f"  --font-{k}: \"{v}\", {'ui-monospace, monospace' if k == 'mono' else 'system-ui, sans-serif'};" for k, v in fonts.items()]
    css += [f"  --text-{k}: {v['css']};" for k, v in scale.items()]
    css += [f"  --space-{s}: {s * sp['base'] / 16:g}rem;" for s in sp["steps"]]
    css += [f"  --radius-{k}: {v}px;" for k, v in radius.items()]
    css += [f"  --shadow-{k}: {v};" for k, v in shadow.items()]
    css += [f"  --duration-{k}: {v}ms;" for k, v in motion["durations"].items()]
    css += [f"  --ease-{k}: cubic-bezier({', '.join(map(str, v))});" for k, v in motion["easings"].items()]
    css.append("}")
    if colors.get("dark"):
        css += ["@media (prefers-color-scheme: dark) {", '  :root:not([data-theme="light"]) {', "    color-scheme: dark;",
                cblock(colors["dark"], "    "), "  }", "}", ':root[data-theme="dark"] {', "  color-scheme: dark;",
                cblock(colors["dark"], "  "), "}"]
    css += ["@media (prefers-reduced-motion: reduce) {", "  :root { --duration-reveal: 1ms; --duration-open: 1ms; }", "}",
            "::selection { background: var(--color-selection); color: var(--color-ink); }",
            ":focus-visible { outline: 2px solid var(--color-focus); outline-offset: 2px; }"]

    # ---- Tailwind v4 (self-contained: --ds-* raw values switch by theme, @theme inline maps utilities)
    def dsblock(T, ind):
        return "\n".join(f"{ind}--ds-{k}: {v};" for k, v in T.items())
    tw = ['@import "tailwindcss";', "", ":root {", dsblock(colors["light"], "  "), "}"]
    if colors.get("dark"):
        tw += ["@media (prefers-color-scheme: dark) {", '  :root:not([data-theme="light"]) {', dsblock(colors["dark"], "    "),
               "  }", "}", ':root[data-theme="dark"] {', dsblock(colors["dark"], "  "), "}"]
    tw += ["", "@theme inline {"]
    tw += [f"  --color-{k}: var(--ds-{k});" for k in colors["light"].keys()]
    tw += ["}", "", "@theme {"]
    tw += [f"  --font-{k}: \"{v}\", {'ui-monospace, monospace' if k == 'mono' else 'system-ui, sans-serif'};" for k, v in fonts.items()]
    tw += [f"  --text-{k}: {v['css']};" for k, v in scale.items()]
    tw += [f"  --radius-{k}: {v}px;" for k, v in radius.items()]
    tw += [f"  --shadow-{k}: {v};" for k, v in shadow.items()]
    tw += [f"  --ease-{k}: cubic-bezier({', '.join(map(str, v))});" for k, v in motion["easings"].items()]
    tw += ["}", "", "@custom-variant dark (&:where([data-theme=dark], [data-theme=dark] *));"]

    out = Path(outdir); out.mkdir(parents=True, exist_ok=True)
    (out / f"{sl}.tokens.json").write_text(json.dumps(tok, indent=2, ensure_ascii=False))
    (out / "tokens.css").write_text("\n".join(css) + "\n")
    (out / "tailwind-theme.css").write_text("\n".join(tw) + "\n")
    print(f"wrote {out}/{sl}.tokens.json, tokens.css, tailwind-theme.css")
    print("type scale (px min..max @390..1440):", ", ".join(f"{k} {v['min']:.0f}-{v['max']:.0f}" for k, v in scale.items()))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("init")
    b = sub.add_parser("build"); b.add_argument("spec"); b.add_argument("--out", default="design-tokens")
    a = ap.parse_args()
    if a.cmd == "init":
        print(json.dumps(STARTER, indent=2))
    else:
        spec = json.load(open(a.spec))
        spec["_dir"] = str(Path(a.spec).resolve().parent)
        build(spec, a.out)


if __name__ == "__main__":
    main()
